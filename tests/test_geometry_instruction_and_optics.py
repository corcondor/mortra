def test_wave_optics_geometric_roundtrip():
    """Verify: scene bitmap -> target intensity -> phase retrieval -> wave propagation -> binarization -> recognition."""
    # 1. Geometric scene: construct letter 'P'
    names, program, coords = constr.build_lattice(6, 6)
    replayed = constr.replay(program)
    named_alphabet = constr.as_names(alpha.ROMAN, names)
    built_letters = constr.as_coordinates(named_alphabet, replayed)
    built_p = built_letters["P"]

    scale = 8
    radius = Fraction(3, 8) * scale
    segs = [
        (
            (Fraction(a[0]) * scale, Fraction(a[1]) * scale),
            (Fraction(b[0]) * scale, Fraction(b[1]) * scale),
        )
        for a, b in raster.polyline_segments(built_p)
    ]
    w = 64
    h = 64
    moved = [
        (
            (a[0] + 12 * scale // 4, a[1] + 8 * scale // 4),
            (b[0] + 12 * scale // 4, b[1] + 8 * scale // 4),
        )
        for a, b in segs
    ]
    scene_bitmap = raster.render(moved, radius, w, h)
    assert scene_bitmap.count() > 0

    # 2. Convert scene_bitmap directly into wave optics target intensity (no redrawing!)
    target_intensity = np.zeros((h, w), dtype=np.float64)
    for x, y in scene_bitmap.black:
        target_intensity[y, x] = 1.0

    # Physical parameters
    wavelength = 532e-9  # 532 nm
    dx = 10e-6  # 10 um pitch
    grid = GridSpec2D(nx=w, ny=h, dx=dx, dy=dx)
    z = 0.008  # 8 mm propagation distance (z < z_crit)

    # 3. Phase retrieval via Gerchberg-Saxton
    optical_train = OpticalTrain()
    optical_train.add(FresnelPropagation(distance=z, wavelength=wavelength))
    input_amplitude = np.ones((h, w), dtype=np.float64)

    phase_slm, errors = phase_retrieval_gerchberg_saxton(
        target_intensity=target_intensity,
        optical_train=optical_train,
        input_amplitude=input_amplitude,
        grid=grid,
        wavelength=wavelength,
        iterations=15,
    )
    assert len(errors) == 15
    assert errors[-1] < errors[0]

    # 4. Forward wave propagation to sensor plane
    field_in = WaveField2D(
        u=input_amplitude * np.exp(1j * phase_slm),
        grid=grid,
        wavelength=wavelength,
        z=0.0,
    )
    field_sensor = optical_train.apply(field_in)
    i_sensor = field_sensor.intensity()

    # 5. Objective binarization condition (Otsu thresholding, no arbitrary tuning)
    # Normalize sensor intensity to [0, 255] integer bins for Otsu calculation
    norm_i = (i_sensor - np.min(i_sensor)) / (np.max(i_sensor) - np.min(i_sensor) + 1e-12)
    hist, bin_edges = np.histogram(norm_i, bins=64, range=(0.0, 1.0))
    prob = hist / float(np.sum(hist))
    omega = np.cumsum(prob)
    mu = np.cumsum(prob * np.arange(len(prob)))
    mu_t = mu[-1]

    # Maximize between-class variance
    sigma_b_squared = np.zeros(len(prob))
    for t in range(len(prob)):
        if 0 < omega[t] < 1.0:
            sigma_b_squared[t] = ((mu_t * omega[t] - mu[t]) ** 2) / (omega[t] * (1.0 - omega[t]))
    best_bin = np.argmax(sigma_b_squared)
    threshold_val = bin_edges[best_bin]

    # Convert back to Bitmap using objective condition
    reconstructed_black = {
        (x, y)
        for y in range(h)
        for x in range(w)
        if norm_i[y, x] >= threshold_val
    }
    reconstructed_bitmap = raster.Bitmap(w, h, reconstructed_black)
    assert reconstructed_bitmap.count() > 0

    # 6. Re-read using geometric reader
    lib = reading.library_from(built_letters)
    read_res = reading.read(reconstructed_bitmap, lib)
    assert read_res["letter"] == "P"


def test_checkpoint_and_acquired_library_persistence(tmp_path):
    """Verify AcquiredLibrary serialization and checkpoint restore semantics."""
    from math_os_prototype import geometry_acquired_library as acqlib
    import subprocess

    # 1. AcquiredLibrary to_dict and from_dict roundtrip
    lib = acqlib.AcquiredLibrary()
    prog = {
        "params": ["p0", "p1"],
        "steps": [{"out": "s0", "prim": "midpoint", "args": ["p0", "p1"]}],
        "result": "s0",
    }
    lib.register(prog, {("midp", ("v", "p0", "p1")): {"test": True}}, source={"task": "t1"})
    state_dict = lib.to_dict()

    lib_restored = acqlib.AcquiredLibrary.from_dict(state_dict)
    assert len(lib_restored.acquired) == 1
    assert lib_restored.holds(prog)

    # 2. Checkpoint restoration script in initial mode
    res_init = subprocess.run(
        [sys.executable, str(repo_root / "scripts" / "restore_or_init_checkpoint.py"), "--mode", "initial"],
        capture_output=True,
        text=True,
    )
    assert res_init.returncode == 0
    assert (repo_root / "reports" / "checkpoint_manifest.json").exists()

    # 3. Checkpoint restoration script in continuous mode with existing dir
    res_cont = subprocess.run(
        [
            sys.executable,
            str(repo_root / "scripts" / "restore_or_init_checkpoint.py"),
            "--mode",
            "continuous",
            "--checkpoint",
            "reports",
        ],
        capture_output=True,
        text=True,
    )
    assert res_cont.returncode == 0

    # 4. Checkpoint restoration script in continuous mode with missing checkpoint must fail (code 1)
    res_fail = subprocess.run(
        [
            sys.executable,
            str(repo_root / "scripts" / "restore_or_init_checkpoint.py"),
            "--mode",
            "continuous",
            "--checkpoint",
            str(tmp_path / "non_existent"),
        ],
        capture_output=True,
        text=True,
    )
    assert res_fail.returncode == 1
    assert "Cannot silently fall back to initial state" in res_fail.stderr

def test_instruction_parser_valid_and_invalid():
    """Verify that valid commands generate distinct tasks and invalid commands are rejected."""
    external_pts = {"a": [0, 0], "b": [4, 0], "c": [2, 3]}

    # Valid command 1: PERP
    res_perp = parser.parse_geometric_instruction("PERP", external_pts)
    assert res_perp["valid"] is True
    assert res_perp["command"] == "PERP"
    assert res_perp["task"]["points"] == {"a": [0, 0], "b": [4, 0], "c": [2, 3]}
    assert any(g["predicate"] == "perp" for g in res_perp["task"]["goals"])

    # Valid command 2: MIDP
    res_midp = parser.parse_geometric_instruction("MIDP", external_pts)
    assert res_midp["valid"] is True
    assert res_midp["command"] == "MIDP"
    assert res_midp["task"]["points"] == {"a": [0, 0], "b": [4, 0]}
    assert any(g["predicate"] == "cong" for g in res_midp["task"]["goals"])
    # Distinct tasks
    assert res_perp["task"] != res_midp["task"]

    # Missing external points
    res_missing = parser.parse_geometric_instruction("PERP", {"a": [0, 0], "b": [4, 0]})
    assert res_missing["valid"] is False
    assert "Missing required external points" in res_missing["reason"]
    assert res_missing["task"] is None

    # Invalid command: FOOBAR
    res_invalid = parser.parse_geometric_instruction("FOOBAR", external_pts)
    assert res_invalid["valid"] is False
    assert "Unknown or unsupported" in res_invalid["reason"]
    assert res_invalid["task"] is None



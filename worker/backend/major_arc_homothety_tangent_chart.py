Point = sp.Matrix


def _canonical(value: sp.Expr, unit_basis: sp.GroebnerBasis) -> str:
    numerator, _ = sp.together(value).as_numer_denom()
    _, remainder = unit_basis.reduce(sp.expand(numerator))
    return str(sp.factor(remainder))


def _dot(left: Point, right: Point) -> sp.Expr:
    return left.dot(right)


def _cross(left: Point, right: Point) -> sp.Expr:
    return left[0] * right[1] - left[1] * right[0]


def _distance_squared(left: Point, right: Point) -> sp.Expr:
    return _dot(left - right, left - right)


@dataclass(frozen=True)
class MajorArcHomothetyTangentCertificate:
    theorem: str
    assumptions: tuple[str, ...]
    discharged_conditions: dict[str, str]
    upstream_semantics: tuple[str, ...]
    normalization: str
    representation_chart: tuple[str, ...]
    proof_dag: tuple[str, ...]
    domain_sign_certificate: dict[str, str]
    replay_residuals: dict[str, str]
    replayed: bool
    all_conditions_discharged: bool
    certificate_sha256: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)

    def to_markdown(self) -> str:
        residuals = "\n".join(
            f"- `{name}`: `{value}`" for name, value in self.replay_residuals.items()
        )
        signs = "\n".join(
            f"- `{name}`: {value}"
            for name, value in self.domain_sign_certificate.items()
        )
        return "\n".join(
            (
                "# Major-arc homothety / tangent-circle chart",
                "",
                "## Theorem",
                "",
                (
                    "For the typed construction in the chart, the incenter axis "
                    "is tangent to the circumcircle of the reflected "
                    "parallelogram/projection triangle."
                ),
                "",
                "## Reusable proof",
                "",
                "1. The ratio-1/2 homothety about A sends P,Q,R to M,N,U.",
                "2. If S is the midpoint of AI, then U is the foot from A to SN.",
                "3. The right-triangle similarity gives SU*SN=SA^2=SI^2.",
                "4. For the antipodal arc midpoint D, DM*DN=DB^2=DI^2.",
                "5. Hence the circles IUN and IMN are both tangent to AI at I.",
                "6. Uniqueness gives I,M,N,U concyclic; homothety returns the goal.",
                "",
                "## Domain and branch certificate",
                "",
                signs,
                "",
                "## Exact replay",
                "",
                residuals,
                "",
                f"- all identities replayed: `{self.replayed}`",
                f"- all conditions discharged: `{self.all_conditions_discharged}`",
                f"- certificate SHA-256: `{self.certificate_sha256}`",
                "",
            )
        )



"""Exact major-arc / homothety / tangent-circle chart.

The reusable chain is

    midpoint of the arc through the vertex
      -> antipodal second arc midpoint on the incenter axis
      -> homothety of ratio 1/2 about the vertex
      -> two right-circle power identities
      -> uniqueness of the circle through two points tangent to a fixed line.

JGEX only records that the arc midpoint lies on a perpendicular bisector and
the circumcircle.  That syntax has two branches.  The application therefore
requires a hash-bound natural-language atom identifying the arc through the
third vertex; it never selects a branch from a benchmark name.
"""

